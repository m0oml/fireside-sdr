#!/usr/bin/env python3
"""Generate the C++ opcode header and the Python<->C++ conformance vectors.
Usage: gen_cpp_assets.py <app dir>      (run from anywhere; imports firesidectl from this directory)"""
import os, sys, struct
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE); sys.path.insert(0, os.path.join(HERE, "tests"))
from firesidectl.opcodes import OPCODES
from firesidectl import protocol as P, eeprom as E, startup as S
from eeprom_image import build_trx

app = sys.argv[1]
inc = os.path.join(app, "core/include/fireside/opcodes_gen.h")
vec = os.path.join(app, "tests/vectors")
AT = {"u32": "ArgType::U32", "i32": "ArgType::I32", "f32": "ArgType::F32", None: "ArgType::None"}

lines = ["// GENERATED by tools/gen_cpp_assets.py from tools/firesidectl/opcodes.py. Do not edit.", "#pragma once", "#include <cstddef>", "#include <cstdint>", "",
         "namespace fireside {", "enum class ArgType { None, U32, I32, F32 };",
         "struct OpInfo { uint32_t value; const char* name; char access; ArgType arg1, arg2, result; };",
         "// access: 'r' read, 'w' write, 'x' both, '?' never called by PowerSDR 2.7.2", "inline constexpr OpInfo kOps[] = {"]
for name, (val, acc, args, res) in sorted(OPCODES.items(), key=lambda kv: kv[1][0]):
    lines.append(f'    {{{val}, "{name}", \'{"x" if acc == "rw" else acc}\', {AT[args[0]]}, {AT[args[1]]}, {AT[res]}}},')
lines += ["};", f"inline constexpr size_t kOpCount = {len(OPCODES)};", "}  // namespace fireside", ""]
open(inc, "w").write("\n".join(lines))

# ---- protocol vectors
cases = [(0, 1221, 0, 0), (1, 1200, 0, 0), (65535, 1347, 0x03A29C77, P.pack_arg(7.1, "f32")), (7, 1244, P.pack_arg(14.2345, "f32"), 0),
         (255, 1219, P.pack_arg(-1, "i32"), P.pack_arg(-5, "i32")), (4660, 1226, 0x0C0F, 0), (2, 1295, 0, 0xFFFFFFFF), (300, 1000, 0xDEADBEEF, 0x12345678)]
with open(os.path.join(vec, "frames.txt"), "w") as f:
    f.write("# id opcode d1 d2 frame(ascii)\n")
    for i, op, d1, d2 in cases:
        f.write(f"{i} {op} {d1} {d2} {P.encode_request(i, op, d1, d2).hex()}\n")
with open(os.path.join(vec, "replies.txt"), "w") as f:
    f.write("# id value frame(hex)\n")
    for i, v in [(0, 0), (9, 3), (65535, 0xFFFFFFFF), (1234, P.pack_arg(14.2, "f32")), (7, 0x02010408)]:
        f.write(f"{i} {v} {P.encode_reply(i, v).hex()}\n")
with open(os.path.join(vec, "tw.txt"), "w") as f:
    f.write("# freq_mhz tuning_word\n")
    for mhz in (0.1, 1.8, 3.7, 7.1, 14.2345, 29.7, 50.313, 54.0, 64.999):
        f.write(f"{mhz!r} {S.freq_to_tw(mhz)}\n")

# ---- EEPROM vectors
good = build_trx()
bad = bytearray(good); bad[0x2E0 + 5] ^= 0x10; bad = bytes(bad)
def expect(img):
    d = E.decode(img, "TRX"); h = d["header"]; L = []
    L += [f"serial={h['serial']}", f"last_cal={h['last_cal']}", f"checksums_present={int(h['checksums_present'])}", f"image_version={h['image_version']}"]
    L += [f"table={t['name']}|{int(t['pointer_ok'])}|{int(t['checksum_ok'])}|{t['checksum_stored']}|{t['checksum_calc']}|{int(t['has_nan'])}|{'-' if t['in_range'] is None else int(t['in_range'])}" for t in d["tables"]]
    L += [f"unverified={len(d['unverified'])}", f"tx_carrier={len(d['tx_carrier']['entries'])}", f"tx_terminated={int(d['tx_carrier']['terminated'])}", f"problems={len(d['problems'])}"]
    L += [f"first_value={d['tables'][0]['values'][0][0]!r}"]
    return "\n".join(L) + "\n"
open(os.path.join(vec, "trx.bin"), "wb").write(good); open(os.path.join(vec, "trx.expect"), "w").write(expect(good))
open(os.path.join(vec, "trx_bad.bin"), "wb").write(bad); open(os.path.join(vec, "trx_bad.expect"), "w").write(expect(bad))
open(os.path.join(vec, "trx.csv"), "w").write(E.csv_text(good))
print(f"{len(OPCODES)} opcodes, {len(cases)} frame vectors, trx.bin {len(good)} bytes -> {app}")
