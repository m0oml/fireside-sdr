#!/usr/bin/env python3
"""Generate analysis/opcode-reference.md from PowerSDR's FWC wrappers.
Usage: gen_opcode_docs.py <powersdr Source dir> <out.md>"""
import re, sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).parent))
from firesidectl.opcodes import OPCODES
from firesidectl.client import DANGEROUS
from opcode_notes import NOTES

src = pathlib.Path(sys.argv[1]); out = pathlib.Path(sys.argv[2])
fwc = (src / "Console/FWC/fwc.cs").read_text(errors="replace").replace("\r", "")

def split_args(s):
    parts, depth, cur = [], 0, ""
    for ch in s:
        if ch in "([": depth += 1
        if ch in ")]": depth -= 1
        if ch == "," and depth == 0: parts.append(cur.strip()); cur = ""
        else: cur += ch
    if cur.strip(): parts.append(cur.strip())
    return parts

sig_re = re.compile(r"public static ([\w<>\[\]]+)\s+(\w+)\s*\(([^)]*)\)([^\n{]*)")
call_re = re.compile(r"PalManager\.Instance\.(ReadOp[12]|WriteOp[1-4])\(\s*(?:PowerSDR\.)?Opcode\.(\w+)\s*,(.*?)\)\s*;", re.S)
sigs = [(m.start(), m) for m in sig_re.finditer(fwc)]
wrappers = {}     # opcode name -> [dict]
for m in call_re.finditer(fwc):
    prior = [s for s in sigs if s[0] < m.start()]
    if not prior: continue
    pos, sm = prior[-1]
    line_no = fwc.count("\n", 0, pos) + 1
    above = []
    for l in reversed(fwc[:pos].split("\n")[:-1]):
        l = l.strip()
        if l.startswith("//"): above.append(l.lstrip("/ ").strip())
        elif l == "": continue
        else: break
    trailing = sm.group(4).strip().lstrip("/ ").strip()
    a = split_args(m.group(3))
    wrappers.setdefault(m.group(2), []).append(dict(
        name=sm.group(2), params=sm.group(3).strip(), kind=m.group(1), d1=a[0] if a else "", d2=a[1] if len(a) > 1 else "",
        comment=" ".join(reversed(above) if above else []) + (" " + trailing if trailing else ""), line=line_no))

# usage outside the wrapper file
app_files = [p for p in (src / "Console").rglob("*.cs") if p.name != "fwc.cs"]
usage = {}
for p in app_files:
    t = p.read_text(errors="replace")
    factory = "FWC" in p.parts and p.name not in ("fwc_midi.cs", "fwc_eeprom.cs", "fwc_atu.cs")
    for w in set(re.findall(r"FWC\.(\w+)\(", t)):
        k = usage.setdefault(w, [0, 0]); k[1 if factory else 0] += len(re.findall(r"FWC\." + w + r"\(", t))

groups = [("Identity, status and firmware", r"GET_(MODEL|SERIAL|FIRMWARE|STATUS|REGION)|_(OK|REV|SN)$|INITIALIZE|GET_TRX|GET_PA_|GET_RFIO|GET_ATU|GET_RX2|GET_VU"),
          ("Tuning and receive path", r"FREQ|RX1_|RX2_|_RX_|PREAMP|ATT|FILTER|_ANT|LOOP|DSP_MODE|QSD|MUX|TAP|DDS|SAMPLE"),
          ("Audio codec and outputs", r"CODEC|SPKR|HEADPHONE|CHANNEL|MUTE|VOL"),
          ("Transmit and keying", r"MOX|TX|_TR$|FULL_DUPLEX|AMP_|RCA_|PDRV|BREAK|IAMBIC|CW_|XV|PTT|KEY"),
          ("ATU", r"ATU"), ("EEPROM and registers", r"EEPROM|REG|POT|RDAC|GPIO|I2C|FIRESIDEWIRE|PIO|CLOCK|PLL"),
          ("PA, fan and power", r"PA_|FAN|POWER|BIAS|STANDBY|PWRBT|RESET|ADC"),
          ("VU (VHF/UHF) module", r"VU_|FWC_OP"), ("Other", r".")]
def group_of(n):
    for g, rx in groups:
        if re.search(rx, n): return g
    return "Other"

def klass(name, acc):
    if acc in ("r", "rw"): return "read"
    if "EEPROM" in name and "WRITE" in name: return "**BLOCKED** (EEPROM)"
    return "dangerous" if (DANGEROUS.search(name) or acc == "?") else "write"

rows = {}
for name, (val, acc, args, res) in OPCODES.items():
    short = re.sub(r"^(RDAL_OP_|FWC_OP_)", "", name)
    rows.setdefault(group_of(short), []).append((val, short, name, acc, args, res))

L = ["# FLEX-5000 opcode reference", "",
     "GENERATED by `tools/gen_opcode_docs.py` from PowerSDR 2.7.2 `Console/FWC/fwc.cs`, plus hand-written notes in `tools/opcode_notes.py`.",
     "Codec writes are gated as 'dangerous' by firesidectl until reviewed (they only affect audio levels/routing, so this may be relaxed later). Nothing here has been verified on hardware. 'safety' is firesidectl's gate class. 'uses' = call sites outside fwc.cs: main app / factory-test forms.", "",
     "Wire format of every request: opcode, data1, data2 (each 32 bits). Arg types: u32, i32, f32 (IEEE float bits). Reads return one 32-bit word.",
     "The same words are used on both transports (MIDI SysEx and the FireWire mailbox).", ""]
total_doc = 0
for g, _ in groups:
    if g not in rows: continue
    L += [f"## {g}", "", "| # | opcode | R/W | safety | PowerSDR wrapper(s) -> data1 / data2 | uses | notes |", "|---|---|---|---|---|---|---|"]
    for val, short, name, acc, args, res in sorted(rows[g]):
        ws = wrappers.get(name, [])
        esc = lambda x: x.replace("|", "\\|")
        def fmt(w):
            c = w["comment"].strip()
            return esc(f"`{w['name']}({w['params']})` -> d1 `{w['d1']}`, d2 `{w['d2']}`" + (f" _{c}_" if c else ""))
        cell = "<br>".join(fmt(w) for w in ws) or "(not called by PowerSDR 2.7.2)"
        u = [0, 0]
        for w in ws:
            k = usage.get(w["name"], [0, 0]); u[0] += k[0]; u[1] += k[1]
        note = NOTES.get(short, "").replace("|", "\\|")
        total_doc += bool(note)
        t = f"{args[0]},{args[1]}" if acc not in ("r", "rw") else f"{args[0]},{args[1]} -> {res}"
        L.append(f"| {val} | `{short}` | {acc} | {klass(name, acc)} | {cell}<br>_types: {t}_ | {u[0]}/{u[1]} | {note} |")
    L.append("")
out.write_text("\n".join(L).replace("|  |", "| |"))
n_w = sum(1 for n in OPCODES if n in wrappers)
print(f"{len(OPCODES)} opcodes, {n_w} with wrappers, {total_doc} with hand notes -> {out}")
missing = [k for k in NOTES if not any(n.endswith(k) for n in OPCODES)]
if missing: print("WARNING notes for unknown opcodes:", missing)
