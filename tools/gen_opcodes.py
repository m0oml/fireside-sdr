#!/usr/bin/env python3
"""Generate firesidectl/opcodes.py from PowerSDR's OpCode.cs and its call sites.

Usage: gen_opcodes.py <powersdr Source dir> <out.py>
Computes implicit C# enum numbering and records, per opcode, how PowerSDR calls
it (ReadOp1/2, WriteOp1-4) so the types of data1/data2 and the result are known.
"""
import re, sys, pathlib

src = pathlib.Path(sys.argv[1]); out = pathlib.Path(sys.argv[2])
text = (src / "PowerSDR.Shared/OpCode.cs").read_text(errors="replace")
text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
body = text[text.index("enum Opcode"):]
body = body[body.index("{") + 1: body.index("}")]
ops, nxt = {}, None
for line in body.splitlines():
    line = re.sub(r"//.*", "", line).strip().rstrip(",")
    if not line:
        continue
    m = re.fullmatch(r"([A-Za-z_0-9]+)\s*(?:=\s*(\w+))?", line)
    if not m:
        print("skip:", line, file=sys.stderr); continue
    name, val = m.groups()
    nxt = (int(val, 0) if val else nxt + 1)
    ops[name] = nxt

# call-site usage
usage = {}
pat = re.compile(r"\b(ReadOp[12]|WriteOp[1-4])\(\s*(?:PowerSDR\.)?Opcode\.([A-Za-z_0-9]+)")
for f in (src / "Console").rglob("*.cs"):
    for kind, name in pat.findall(f.read_text(errors="replace")):
        usage.setdefault(name, set()).add(kind)

W = {"WriteOp1": ("u32", "u32"), "WriteOp2": ("f32", "u32"),
     "WriteOp3": ("i32", "i32"), "WriteOp4": ("u32", "f32")}
lines = ['"""GENERATED by tools/gen_opcodes.py from PowerSDR OpCode.cs. Do not edit."""', "",
         "# name: (value, access, arg_types, result_type)",
         "# access: 'r' read, 'w' write, 'rw' both seen, '?' never called by PowerSDR 2.7.2",
         "OPCODES = {"]
for name, val in sorted(ops.items(), key=lambda kv: kv[1]):
    u = usage.get(name, set())
    reads = sorted(k for k in u if k.startswith("Read"))
    writes = sorted(k for k in u if k.startswith("Write"))
    access = "rw" if reads and writes else "r" if reads else "w" if writes else "?"
    args = W[writes[0]] if writes else ("u32", "u32")
    # PowerSDR reads some opcodes both ways (e.g. EEPROM words as uint and as float): the wire value is
    # the same 32 bits, so default to u32 unless the opcode is ONLY ever read as float.
    res = "u32" if "ReadOp1" in reads else "f32" if "ReadOp2" in reads else None
    lines.append(f"    {name!r}: ({val}, {access!r}, {args!r}, {res!r}),")
lines += ["}", "", "BY_VALUE = {v[0]: k for k, v in OPCODES.items()}", ""]
out.write_text("\n".join(lines))
n = len(ops); c = {a: sum(1 for k in ops if (("rw" if (any(x.startswith('Read') for x in usage.get(k,())) and any(x.startswith('Write') for x in usage.get(k,()))) else "r" if any(x.startswith('Read') for x in usage.get(k,())) else "w" if usage.get(k) else "?") == a)) for a in ("r","w","rw","?")}
print(f"{n} opcodes -> {out}  {c}")
