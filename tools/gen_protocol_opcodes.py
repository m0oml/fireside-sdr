#!/usr/bin/env python3
"""Generate protocol/04-opcodes.md, opcodes.json and opcodes.csv from the opcode table (firesidectl/opcodes.py) and the hand notes (opcode_notes.py).
Needs no PowerSDR source. Also writes the machine-readable protocol/opcodes.json and opcodes.csv. Usage: gen_protocol_opcodes.py [output directory]   (default: ../protocol)
'In use' = the opcode's name appears in the C++ sources of the app (app/core, app/gui; not the simulator, the generated table or the policy lists), i.e. Fireside SDR sends it to a real radio."""
import pathlib, re, sys
HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from firesidectl.opcodes import OPCODES
from firesidectl.client import DANGEROUS
from opcode_notes import NOTES

ROOT = HERE.parent
GROUPS = [("Identity, status and firmware", r"GET_(MODEL|SERIAL|FIRMWARE|STATUS|REGION)|_(OK|REV|SN)$|INITIALIZE|GET_TRX|GET_PA_|GET_RFIO|GET_ATU|GET_RX2|GET_VU"),
          ("Tuning and receive path", r"FREQ|RX1_|RX2_|_RX_|PREAMP|ATT|FILTER|_ANT|LOOP|DSP_MODE|QSD|MUX|TAP|DDS|SAMPLE"),
          ("Audio codec and outputs", r"CODEC|SPKR|HEADPHONE|CHANNEL|MUTE|VOL"),
          ("Transmit and keying", r"MOX|TX|_TR$|FULL_DUPLEX|AMP_|RCA_|PDRV|BREAK|IAMBIC|CW_|XV|PTT|KEY"),
          ("ATU", r"ATU"), ("EEPROM and registers", r"EEPROM|REG|POT|RDAC|GPIO|I2C|FLEXWIRE|PIO|CLOCK|PLL"),
          ("PA, fan and power", r"PA_|FAN|POWER|BIAS|STANDBY|PWRBT|RESET|ADC"),
          ("VU (VHF/UHF) module", r"VU_|FWC_OP"), ("Other", r".")]

def group_of(n):
    return next(g for g, rx in GROUPS if re.search(rx, n))

def safety(name, acc):
    if acc in ("r", "rw"): return "read"
    if "EEPROM" in name and "WRITE" in name: return "**never** (EEPROM)"
    return "dangerous" if (DANGEROUS.search(name) or acc == "?") else "write"

def clean(note):
    """Drop references to source files and line numbers: the reader does not have them."""
    note = re.sub(r"\s*\([^)]*\.cs[^)]*\)", "", note)
    note = re.sub(r"\s*\((?:InitRadio|chkPower|Misc\.[A-Za-z]+)[^)]*\)", "", note)
    note = re.sub(r"\bconsole\w*\.cs\b[^.;]*", "", note)
    return note.replace("|", "\\|").strip()

def sources_text():
    t = ""
    skip = ("opcodes_gen.h", "safety.cpp")          # the generated table and the policy lists send nothing
    for d in ("app/core/src", "app/core/include", "app/gui"):
        for p in (ROOT / d).rglob("*"):
            if p.suffix in (".cpp", ".h") and p.name not in skip and not p.name.startswith("sim_"):
                t += p.read_text(errors="replace")
    return t

def table():
    """All opcodes as dicts, for the machine-readable files: number, name, access, types, safety, in_use, note."""
    text = sources_text(); out = []
    for name, (val, acc, args, res) in sorted(OPCODES.items(), key=lambda kv: kv[1][0]):
        short = re.sub(r"^(RDAL_OP_|FWC_OP_)", "", name)
        out.append({"number": val, "name": short, "access": acc, "data1": args[0], "data2": args[1], "result": res if acc in ("r", "rw") else None,
                    "safety": safety(name, acc).replace("**", ""), "in_use": bool(re.search(r"\b(?:RDAL_OP_|FWC_OP_)?" + re.escape(short) + r"\b", text)),
                    "group": group_of(short), "note": clean(NOTES.get(short, "")).replace("\\|", "|")})
    return out

def build_json():
    import json
    return json.dumps({"description": "FLEX-5000 opcodes (see protocol/04-opcodes.md). Generated by tools/gen_protocol_opcodes.py.",
                       "access": {"r": "returns a value", "w": "no return value", "?": "direction not documented"},
                       "opcodes": table()}, indent=1) + "\n"

def build_csv():
    import csv, io
    f = io.StringIO(); w = csv.writer(f, lineterminator="\n")
    w.writerow(["number", "name", "access", "data1", "data2", "result", "safety", "in_use", "group", "note"])
    for o in table(): w.writerow([o["number"], o["name"], o["access"], o["data1"], o["data2"], o["result"] or "", o["safety"], "yes" if o["in_use"] else "", o["group"], o["note"]])
    return f.getvalue()

def build():
    text = sources_text()
    def in_use(name):
        short = re.sub(r"^(RDAL_OP_|FWC_OP_)", "", name)
        return bool(re.search(r"\b(?:RDAL_OP_|FWC_OP_)?" + re.escape(short) + r"\b", text))
    rows, bare = {}, []
    for name, (val, acc, args, res) in OPCODES.items():
        short = re.sub(r"^(RDAL_OP_|FWC_OP_)", "", name)
        note = clean(NOTES.get(short, ""))
        if acc == "?" and not note: bare.append((val, short)); continue
        rows.setdefault(group_of(short), []).append((val, short, acc, args, res, safety(name, acc), in_use(name), note))
    L = ["# 4. Opcode reference", "",
         "Every request is `opcode, data1, data2` (three 32-bit words, see page 2). Argument types: `u32`, `i32`, `f32` (IEEE-754 bits, tuning frequencies are MHz). A read returns one 32-bit word.",
         "",
         "**Columns.** *R/W*: `r` the opcode returns a value, `w` it does not, `?` the direction is not documented. *Safety* is the class Fireside SDR enforces:",
         "`read` is always allowed; `write` changes radio state; `dangerous` can key the transmitter, move relays or change bias and needs a deliberate decision; `never` is not sent by",
         "anything in this repository. *In use* marks opcodes Fireside SDR sends to a real radio. Everything else comes from published open-source code and is **Reported**, not verified.",
         "",
         "This page is generated by `tools/gen_protocol_opcodes.py`. Add knowledge in `tools/opcode_notes.py`, not here.",
         "The same table for programs: [`opcodes.json`](opcodes.json) and [`opcodes.csv`](opcodes.csv).", ""]
    for g, _ in GROUPS:
        if g not in rows: continue
        L += [f"## {g}", "", "| # | opcode | R/W | types | safety | in use | notes |", "|---|---|---|---|---|---|---|"]
        for val, short, acc, args, res, sf, used, note in sorted(rows[g]):
            t = f"{args[0]}, {args[1]}" + (f" -> {res}" if acc in ("r", "rw") and res else "")
            L.append(f"| {val} | `{short}` | {acc} | {t} | {sf} | {'yes' if used else ''} | {note} |")
        L.append("")
    L += ["## Opcodes with no documented use", "",
          "The firmware's opcode list includes these, but no published code calls them and nothing is known about them. **Do not send them**: they include factory, calibration and",
          "test functions. Listed so that you can recognise a number you see elsewhere.", "",
          ", ".join(f"`{s}` ({v})" for v, s in sorted(bare)), ""]
    return "\n".join(L).replace("|  |", "| |")

if __name__ == "__main__":
    d = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "protocol"
    for name, text in (("04-opcodes.md", build()), ("opcodes.json", build_json()), ("opcodes.csv", build_csv())):
        (d / name).write_text(text); print("wrote", d / name)
